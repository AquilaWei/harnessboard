// Writes THIRD-PARTY-NOTICES.md: the licenses of the packages that end up inside the web
// bundle (`packages/server/dist/web`). Run it after changing the web dependencies:
//   node scripts/third-party-notices.mjs
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const list = JSON.parse(
  execFileSync('pnpm', ['--filter', '@harnessboard/web', 'licenses', 'list', '--prod', '--json'], {
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  }),
);

const entries = Object.values(list)
  .flat()
  .flatMap((pkg) => pkg.versions.map((version, i) => ({ ...pkg, version, path: pkg.paths[i] })))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

/** The package's own license file, if it ships one. */
function licenseText(dir) {
  const file = readdirSync(dir).find((f) => /^(licen[sc]e|copying)(\.|$)/i.test(f));
  return file ? readFileSync(join(dir, file), 'utf8').trim() : null;
}

const missing = [];
const sections = entries.map(({ name, version, license, homepage, path }) => {
  const text = existsSync(path) ? licenseText(path) : null;
  if (!text) missing.push(`${name}@${version}`);
  return [
    `## ${name} ${version}`,
    '',
    `License: ${license}${homepage ? ` · ${homepage}` : ''}`,
    '',
    text ? '```text\n' + text + '\n```' : '_The package ships no license file; see its homepage._',
  ].join('\n');
});

const header = [
  '# Third-party notices',
  '',
  'The Harnessboard web board bundles the packages below. Each is used under its own',
  'license, reproduced here. Harnessboard itself is licensed under Apache-2.0 (see `LICENSE`).',
  '',
  'Generated by `scripts/third-party-notices.mjs`; do not edit by hand.',
  '',
];

writeFileSync(
  new URL('../THIRD-PARTY-NOTICES.md', import.meta.url),
  header.join('\n') + '\n' + sections.join('\n\n') + '\n',
);
console.log(`${entries.length} packages written`);
if (missing.length) console.log(`no license file: ${missing.join(', ')}`);
